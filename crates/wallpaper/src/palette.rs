/// Fraction 0..1 of directional shading on a surface with horizontal slope `slope`
/// (dy/dx in screen space, y down) at column x of a canvas `w` wide.
pub fn lit(pal: &Pal, slope: f32, x: f32, w: f32, gain: f32) -> f32 {
    let dir = ((pal.light_x * w - x) / (w * 0.45)).clamp(-1.0, 1.0);
    (0.62 + gain * pal.light_gain * slope * dir * 2.2).clamp(0.0, 1.0)
}
